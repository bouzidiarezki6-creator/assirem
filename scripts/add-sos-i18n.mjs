function deepMerge(target, source) {
  const output = { ...target }
  for (const [key, value] of Object.entries(source)) {
    if (
      value &&
      typeof value === "object" &&
      !Array.isArray(value) &&
      target[key] &&
      typeof target[key] === "object"
    ) {
      output[key] = deepMerge(target[key], value)
    } else {
      output[key] = value
    }
  }
  return output
}

