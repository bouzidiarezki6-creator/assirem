export type DemoStats = {
  events: number
  activities: number
  institutions: number
  news: number
  announcements: number
  volunteers: number
  operations: number
  sosSites: number
  sosNeeds: number
  sosCalls: number
  totalDemoItems: number
}

export function countDemoStats(data: AppData): DemoStats {
  const countIn = (arr?: any[]) => (arr || []).filter(isDemoRecord).length
  const events = countIn(data.events)
  const activities = countIn(data.activities)
  const institutions = countIn(data.institutions)
  const news = countIn(data.news)
  const announcements = countIn(data.announcements)
  const volunteers = countIn(data.volunteerAccounts)
  const operations = countIn(data.institutionalOperations)
  const sosSites = countIn(data.sosCollectionSites) + countIn(data.sosDamagedSites)
  const sosNeeds = countIn(data.sosMaterialNeeds)
  const sosCalls = countIn(data.sosCalls)

  return {
    events,
    activities,
    institutions,
    news,
    announcements,
    volunteers,
    operations,
    sosSites,
    sosNeeds,
    sosCalls,
    totalDemoItems:
      events +
      activities +
      institutions +
      news +
      announcements +
      volunteers +
      operations +
      sosSites +
      sosNeeds +
      sosCalls,
  }
}

